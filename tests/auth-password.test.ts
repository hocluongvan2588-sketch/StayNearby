import bcrypt from 'bcryptjs';
import { describe, expect, it } from 'vitest';
import { hashPassword, verifyPassword } from '@/lib/auth/password';

describe('Password Hashing & Verification (scrypt + Supabase bcrypt)', () => {
  it('verifies native scrypt hashes generated by hashPassword', () => {
    const hash = hashPassword('StrongPass!2026');
    expect(verifyPassword('StrongPass!2026', hash)).toBe(true);
    expect(verifyPassword('WrongPass!2026', hash)).toBe(false);
  });

  it('verifies Supabase Auth bcrypt ($2a$/$2b$) password hashes', () => {
    const bcryptHash = bcrypt.hashSync('SupaPass!2026', 10);
    expect(bcryptHash.startsWith('$2')).toBe(true);
    expect(verifyPassword('SupaPass!2026', bcryptHash)).toBe(true);
    expect(verifyPassword('WrongPass!2026', bcryptHash)).toBe(false);
  });
});
